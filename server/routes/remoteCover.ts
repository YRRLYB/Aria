import express from "express";
import { z } from "zod";
import type { RemoteCoverCache } from "../remoteCoverCache";

type CoverRequest = Pick<express.Request, "query" | "method" | "fresh" | "headers">;
type CoverResponse = express.Response;

/** Shared cover response logic for the legacy NetEase mount and /api/sources. */
export async function handleCoverRequest(
  cache: RemoteCoverCache,
  req: CoverRequest,
  res: CoverResponse,
): Promise<void> {
  const query = z.object({
    url: z.string().url(),
    size: z.string().regex(/^\d{2,4}[xy]\d{2,4}$/).optional(),
  }).parse(req.query);
  const { contentType, byteLength, etag, filePath, body } = await cache.read(query.url, query.size);
  res.set({
    "Content-Type": contentType,
    "Content-Length": String(byteLength),
    "Cache-Control": "public, max-age=604800, immutable",
    "ETag": etag,
    "X-Content-Type-Options": "nosniff",
  });
  if (req.fresh) { res.status(304).end(); return; }
  if (req.method === "HEAD") { res.end(); return; }
  if (filePath) {
    // The cache can live in .musicbox or another hidden data directory.
    // This path is generated by the cache, never supplied by the request.
    await new Promise<void>((resolve, reject) => {
      res.sendFile(filePath, { cacheControl: false, dotfiles: "allow" }, (error) => {
        if (error && !res.headersSent) {
          for (const header of ["Content-Type", "Content-Length", "Cache-Control", "ETag"]) res.removeHeader(header);
          reject(error);
          return;
        }
        resolve();
      });
    });
    return;
  }
  res.send(body);
}

export function createRemoteCoverRouter(cache: RemoteCoverCache) {
  const router = express.Router();
  router.get("/", async (req, res, next) => {
    try {
      await handleCoverRequest(cache, req, res);
    } catch (error) {
      next(error);
    }
  });
  return router;
}
